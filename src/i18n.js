// Prefix a site-relative URL (path, query and hash) for the given locale.
export function localeHref(locale, href = "/") {
  if (locale !== "id" || !href.startsWith("/") || href.startsWith("//"))
    return href;
  const cut = href.search(/[?#]/);
  const path = cut === -1 ? href : href.slice(0, cut);
  const rest = cut === -1 ? "" : href.slice(cut);
  return "/id" + (path === "/" ? "" : path) + rest;
}

export const formatIDR = (amount, locale = "id") =>
  new Intl.NumberFormat(intlLocale[locale], {
    style: "currency",
    currency: "IDR",
    maximumFractionDigits: 0,
  }).format(amount);

export const formatLongDate = (key, locale = "id") =>
  new Date(`${key}T12:00:00`).toLocaleDateString(intlLocale[locale], {
    day: "numeric",
    month: "long",
    year: "numeric",
  });

